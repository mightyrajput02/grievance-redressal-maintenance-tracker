-- 4_triggers.sql
-- triggers for audit, setting complaint_no, and logging changes

CREATE OR REPLACE TRIGGER trg_complaints_ai
AFTER INSERT ON complaints
FOR EACH ROW
BEGIN
  INSERT INTO complaint_logs (complaint_id, actor_user_id, action, details)
    VALUES (:NEW.complaint_id, :NEW.student_id, 'INSERT_TRIGGER', 'Inserted complaint via trigger' || CASE WHEN :NEW.urgent_flag = 1 THEN ' (URGENT)' ELSE '' END);
END;
/

CREATE OR REPLACE TRIGGER trg_complaints_au
AFTER UPDATE ON complaints
FOR EACH ROW
DECLARE
  l_details VARCHAR2(4000);
BEGIN
  l_details := 'Status: ' || NVL(:NEW.status,'NULL') || '; Assigned: ' || NVL(TO_CHAR(:NEW.assigned_staff_id),'NULL') || '; ExpectedMin: ' || NVL(TO_CHAR(:NEW.expected_resolution_minutes),'NULL');
  INSERT INTO complaint_logs (complaint_id, actor_user_id, action, details)
    VALUES (:NEW.complaint_id, NVL(:NEW.assigned_staff_id, :NEW.student_id), 'UPDATE', l_details);
END;
/

-- 5_scheduler.sql
-- Create a scheduler job to run escalate_due_complaints every 10 minutes

BEGIN
  DBMS_SCHEDULER.CREATE_JOB (
    job_name        => 'GRIEVANCE_ESCALATION_JOB',
