-- 1_create_schema.sql
-- Updated Schema: adds urgent flag, expected/actual resolution minutes, assignments, and resolution stats

-- Users table
CREATE TABLE users (
  user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username      VARCHAR2(100) UNIQUE NOT NULL,
  full_name     VARCHAR2(200),
  role          VARCHAR2(20) NOT NULL CHECK (role IN ('STUDENT','STAFF','ADMIN')),
  email         VARCHAR2(200),
  department_id NUMBER,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Departments
CREATE TABLE departments (
  department_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(200) NOT NULL
);

-- Complaint categories with SLA in hours
CREATE TABLE complaint_categories (
  category_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(200) NOT NULL,
  sla_hours   NUMBER DEFAULT 48 -- default SLA 48 hours
);

-- Complaints (extended)
CREATE TABLE complaints (
  complaint_id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  complaint_no                VARCHAR2(50) UNIQUE,
  student_id                  NUMBER NOT NULL,
  category_id                 NUMBER NOT NULL,
  department_id               NUMBER,
  description                 CLOB,
  created_at                  TIMESTAMP DEFAULT SYSTIMESTAMP,
  status                      VARCHAR2(20) DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','ESCALATED','CLOSED')),
  assigned_staff_id           NUMBER,
  escalation_level            NUMBER DEFAULT 1,
  sla_deadline                TIMESTAMP,
  resolution_attachment_id    NUMBER,
  closed_at                   TIMESTAMP,
  -- New: urgent indicator (1 = urgent)
  urgent_flag                 NUMBER(1) DEFAULT 0,
  -- New: expected resolution estimate in minutes (derived from SLA/category/history/urgent)
  expected_resolution_minutes NUMBER,
  -- New: actual time taken in minutes (stored when resolved)
  resolution_minutes          NUMBER,
  CONSTRAINT fk_c_student FOREIGN KEY (student_id) REFERENCES users(user_id),
  CONSTRAINT fk_c_category FOREIGN KEY (category_id) REFERENCES complaint_categories(category_id),
  CONSTRAINT fk_c_dept FOREIGN KEY (department_id) REFERENCES departments(department_id),
  CONSTRAINT fk_c_assigned FOREIGN KEY (assigned_staff_id) REFERENCES users(user_id)
);

-- Attachments
CREATE TABLE attachments (
  attachment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  complaint_id  NUMBER,
  filename      VARCHAR2(255),
  content_type  VARCHAR2(100),
  content_blob  BLOB,
  is_resolution NUMBER(1) DEFAULT 0, -- 1 means it's proof of resolution
  uploaded_by   NUMBER,
  uploaded_at   TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_a_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(complaint_id) ON DELETE CASCADE,
  CONSTRAINT fk_a_uploader FOREIGN KEY (uploaded_by) REFERENCES users(user_id)
);

-- Complaint logs for audit/history
CREATE TABLE complaint_logs (
  log_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  complaint_id  NUMBER NOT NULL,
  log_at        TIMESTAMP DEFAULT SYSTIMESTAMP,
  actor_user_id NUMBER,
  action        VARCHAR2(100),
  details       CLOB,
  CONSTRAINT fk_log_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(complaint_id)
);

-- Staff hierarchy mapping staff -> manager
CREATE TABLE staff_hierarchy (
  staff_id        NUMBER PRIMARY KEY,
  manager_id      NUMBER,
  hierarchy_level NUMBER DEFAULT 1,
  CONSTRAINT fk_sh_staff FOREIGN KEY (staff_id) REFERENCES users(user_id),
  CONSTRAINT fk_sh_manager FOREIGN KEY (manager_id) REFERENCES users(user_id)
);

-- Notifications
CREATE TABLE notifications (
  notification_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id         NUMBER,
  complaint_id    NUMBER,
  notif_type      VARCHAR2(50),
  payload         CLOB,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP,
  read_flag       NUMBER(1) DEFAULT 0,
  CONSTRAINT fk_n_user FOREIGN KEY (user_id) REFERENCES users(user_id),
  CONSTRAINT fk_n_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(complaint_id)
);

-- New: assignment/queue table tracks assignment events and queue position per worker
CREATE TABLE complaint_assignments (
  assignment_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  complaint_id      NUMBER NOT NULL,
  staff_id          NUMBER NOT NULL,
  assigned_by       NUMBER,
  assigned_at       TIMESTAMP DEFAULT SYSTIMESTAMP,
  queue_position    NUMBER NOT NULL,
  active_assignment NUMBER(1) DEFAULT 1, -- 1 = current active assignment for complaint
  CONSTRAINT fk_ca_complaint FOREIGN KEY (complaint_id) REFERENCES complaints(complaint_id) ON DELETE CASCADE,
  CONSTRAINT fk_ca_staff FOREIGN KEY (staff_id) REFERENCES users(user_id),
  CONSTRAINT fk_ca_assigned_by FOREIGN KEY (assigned_by) REFERENCES users(user_id)
);

-- New: resolution statistics (averages) to compute expected timelines from history
CREATE TABLE complaint_resolution_stats (
  stats_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  category_id     NUMBER NOT NULL,
  worker_id       NUMBER, -- nullable: NULL means aggregated across workers for category
  avg_minutes     NUMBER DEFAULT 0,
  resolved_count  NUMBER DEFAULT 0,
  last_updated    TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_crs_category FOREIGN KEY (category_id) REFERENCES complaint_categories(category_id),
  CONSTRAINT fk_crs_worker FOREIGN KEY (worker_id) REFERENCES users(user_id)
);

-- Helper indexes
CREATE INDEX ix_complaints_student_id ON complaints(student_id);
CREATE INDEX ix_complaints_status_deadline ON complaints(status, sla_deadline);
CREATE INDEX ix_attachments_complaint_id ON attachments(complaint_id);
CREATE INDEX ix_ca_staff_pos ON complaint_assignments(staff_id, queue_position);
CREATE INDEX ix_crs_category_worker ON complaint_resolution_stats(category_id, worker_id);
